export function gerarMacroSaldo() {
  const corpo = corpoMacro();
  const versao = assinatura(corpo);
  const codigo = [
    "' Robo Correcao de Saldo (Excel) - Central de Fretes.",
    "' Cole este codigo num Modulo do Excel (Alt+F11 > Inserir > Modulo) da planilha do robo (Robo Lancamento.xlsm).",
    `' Para rodar: Alt+F8 > ${MACRO_SALDO} (ou o botao com essa macro) e escolha a planilha de dados baixada da Central.`,
    "' Nao edite: quando a Central mudar o robo, ela avisa e voce cola o codigo novo.",
    'Option Explicit',
    '',
    `Private Const VERSAO_MACRO = "${versao}"`,
    corpo,
  ].join('\n');
  return { codigo: codigo.replace(/\r?\n/g, '\r\n') + '\r\n', versao, macro: MACRO_SALDO };
}

// Linhas da planilha de dados. Datas no formato do SAP (dd.mm.aaaa). Sem chaves = corrige todas as do relatorio.
export function matrizDadosSaldo({ chaves = [], dataInicial, dataFinal = '', ignorar = [], central = {}, usuario = '' }) {
  if (!dataSapValida(dataInicial)) throw new Error('Informe a data inicial.');
  if (dataFinal && !dataSapValida(dataFinal)) throw new Error('Data final invalida.');
  const { versao } = gerarMacroSaldo();
  const listaIgnorar = ignorar.map((t) => semAcento(t).toUpperCase().trim()).filter(Boolean).join(',');
  return [
    ['chave', '', `macro ${versao}`, dataInicial, dataFinal, listaIgnorar, central.url || '', central.chave || '', usuario || '', '', 'saldo'],
    ...chaves.map((c) => [String(c)]),
  ];
}
