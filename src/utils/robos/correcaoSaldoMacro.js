// Robo "Correcao de saldo" na planilha unica do robo (Excel .xlsm) — substitui a planilha "Ajuste de saldo".
//
// O que a planilha antiga fazia (macros RelatorioSaldo, RelatorioPedidos e CorrecaoSaldo + Power Query):
//  1. ZMMCTE_PED_LOG no periodo, filtra a mensagem "saldo*" e exporta (CT-esErro);
//  2. ME2L dos pedidos desses CT-e (layout DEFAULT) e exporta (PedidosCTe) -> preco liquido do pedido;
//  3. valor liquido correto = ARRED(var.mensagem 3 x preco liquido / var.mensagem 2; 2)
//     (o fator liquido/bruto do pedido aplicado ao valor do CT-e);
//  4. para cada CT-e: abre o pedido pelo log, troca o valor liquido do servico, salva e reprocessa a linha.
// Aqui a macro faz tudo isso sozinha (sem Power Query) e, no fim, grava a partida de cada CT-e que ficou
// escriturado na base de partidas da Central (rotinas comuns em partidasRoboVba.js).
//
// A cada rodada a Central baixa so os dados (.xlsx, sem codigo): periodo, transportadoras ignoradas,
// endereco da Central e, opcionalmente, as chaves (corrige so essas).

