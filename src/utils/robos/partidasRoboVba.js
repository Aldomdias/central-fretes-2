// Rotinas VBA comuns aos robos que escrituram CT-e no SAP pela ZMMCTE_PED_LOG (Escrituracao/Reprocessar
// e Correcao de saldo): depois de reprocessar, consultam de novo o log so das chaves trabalhadas,
// pegam o documento da MIRO de cada CT-e escriturado e gravam a partida direto na base da Central
// (tabela ctes_lancamentos_sap, mesma do relatorio SAP), sem esperar a importacao do relatorio.
// O formato da linha e o mesmo de partidaDoRobo (src/utils/lancamentosCteSap.js).
//
// O modulo que usa estas rotinas precisa ter: session, PASTA, dataIni, dataFim, urlCentral, chaveCentral,
// AbrirTransacao, Copiar, FecharCopia, SoDigitos e Registrar.

const GRADE = 'wnd[0]/usr/cntlGRID1/shellcont/shell/shellcont[1]/shell';
const EXPORT = 'wnd[1]/usr/ssubSUB_CONFIGURATION:SAPLSALV_GUI_CUL_EXPORT_AS:0512';
export const ARQ_SITUACAO = 'SituacaoCTe';

export function declaracoesPartidasVba() {
  return [
    'Private urlCentral, chaveCentral, usuarioCentral, nPartidas, nPartidasFalha, nSemMiro, nSemValor, nHistorico, nHistoricoFalha',
  ];
}

// origem: "ESCRITURACAO" ou "CORRECAO_SALDO" (vai em arquivo_origem = "ROBO:<origem>").
export function rotinasPartidasVba() {
  const s = (id) => `session.findById("${id}")`;
  return [
    "' Consulta de novo o log so das chaves trabalhadas e grava a partida de quem ganhou documento de MIRO.",
    "' valoresReserva: Dictionary chave -> valor do CT-e (usado quando a base da Central nao tem o CT-e).",
    'Private Sub GravarPartidas(lista, n, valoresReserva, origem)',
    '    Dim miros, transps, pedidos, empresas, valores, k, i, linhasJson, histJson, nLote, cnpj, numero, serie, v, montante, chaveP, csv, por, tipoHist',
    '    nPartidas = 0',
    '    nPartidasFalha = 0',
    '    nSemMiro = 0',
    '    nSemValor = 0',
    '    nHistorico = 0',
    '    nHistoricoFalha = 0',
    '    If n = 0 Then Exit Sub',
    '    If urlCentral = "" Then',
    '        Registrar "partidas: arquivo de dados sem o endereco da Central; nada gravado na base"',
    '        Exit Sub',
    '    End If',
    "    ' quem rodou: o usuario da Central que baixou os dados (senao, o login do Windows)",
    '    por = usuarioCentral',
    '    If por = "" Then por = Environ("USERNAME")',
    '    tipoHist = IIf(origem = "CORRECAO_SALDO", "SALDO", "ESCRITURACAO")',
    '    Set miros = CreateObject("Scripting.Dictionary")',
    '    Set transps = CreateObject("Scripting.Dictionary")',
    '    Set pedidos = CreateObject("Scripting.Dictionary")',
    '    Set empresas = CreateObject("Scripting.Dictionary")',
    '    If Not ExportarSituacao(lista, n) Then Exit Sub',
    '    If Not LerSituacao(miros, transps, pedidos, empresas) Then Exit Sub',
    '    Set valores = BuscarValoresCentral(miros)',
    '    csv = PASTA & "\\partidas_gravadas.csv"',
    '    linhasJson = ""',
    '    histJson = ""',
    '    nLote = 0',
    '    For i = 0 To n - 1',
    '        k = lista(i)',
    '        If Not miros.Exists(k) Then',
    '            nSemMiro = nSemMiro + 1',
    '        Else',
    '            v = 0',
    '            If valores.Exists(k) Then v = valores(k)',
    '            If v <= 0 And Not IsEmpty(valoresReserva) Then',
    '                If valoresReserva.Exists(k) Then v = valoresReserva(k)',
    '            End If',
    '            If v <= 0 Or Mid(k, 21, 2) <> "57" Then',
    '                nSemValor = nSemValor + 1',
    '                Registrar "partida nao gravada (sem valor do CT-e na base): " & k',
    '            Else',
    '                cnpj = Mid(k, 7, 14)',
    '                serie = CStr(CLng(Mid(k, 23, 3)))',
    '                numero = CStr(CLng(Mid(k, 26, 9)))',
    '                montante = -Round(v, 2)',
    '                chaveP = cnpj & "|" & numero & "|" & serie & "|" & miros(k) & "|" & CStr(CLng(Round(montante * 100, 0)))',
    '                If linhasJson <> "" Then linhasJson = linhasJson & ","',
    '                linhasJson = linhasJson & "{""chave"":""" & chaveP & """,""cnpj_emitente"":""" & cnpj & """,""numero_cte"":""" & numero & """,""serie_cte"":""" & serie & """,""referencia"":""" & numero & "-" & serie & """,""fornecedor"":""" & JsonTxt(transps(k)) & """,""lancamento_contabil"":""" & miros(k) & """,""data_lancamento"":""" & Format(Date, "yyyy-mm-dd") & """,""montante"":" & NumJson(montante) & ",""criado_por"":""ROBO CENTRAL (" & JsonTxt(por) & ")"",""texto"":""Lancado pela Central (" & LCase(origem) & ")"",""arquivo_origem"":""ROBO:" & origem & """}"',
    "                ' historico dos robos (Acompanhamento de lancamentos da Central)",
    '                If histJson <> "" Then histJson = histJson & ","',
    '                histJson = histJson & "{""tipo"":""" & tipoHist & """,""documento"":""" & numero & "-" & serie & """,""cnpj_transp"":""" & cnpj & """,""transportadora"":""" & JsonTxt(transps(k)) & """,""empresa"":""" & JsonTxt(empresas(k)) & """,""valor"":" & NumJson(Round(v, 2)) & ",""pedido"":""" & JsonTxt(pedidos(k)) & """,""miro"":""" & miros(k) & """,""lancado_por"":""" & JsonTxt(por) & """}"',
    '                nLote = nLote + 1',
    '                AnexarTexto csv, k & ";" & miros(k) & ";" & Replace(CStr(Round(v, 2)), ".", ",")',
    '                If nLote >= 200 Then',
    '                    EnviarPartidas linhasJson, nLote',
    '                    EnviarHistorico histJson, nLote',
    '                    linhasJson = ""',
    '                    histJson = ""',
    '                    nLote = 0',
    '                End If',
    '            End If',
    '        End If',
    '    Next',
    '    If nLote > 0 Then',
    '        EnviarPartidas linhasJson, nLote',
    '        EnviarHistorico histJson, nLote',
    '    End If',
    '    Registrar "partidas na base da Central: " & nPartidas & " gravada(s), " & nPartidasFalha & " com falha, " & nSemMiro & " sem MIRO no log, " & nSemValor & " sem valor; acompanhamento: " & nHistorico & " gravado(s), " & nHistoricoFalha & " com falha"',
    'End Sub',
    '',
    "' Historico dos robos (robos_lancamentos): aparece no Acompanhamento de lancamentos da Central.",
    'Private Sub EnviarHistorico(histJson, qtd)',
    '    Dim http',
    '    On Error Resume Next',
    '    Set http = CreateObject("MSXML2.XMLHTTP.6.0")',
    '    http.Open "POST", urlCentral & "/rest/v1/robos_lancamentos?on_conflict=tipo,miro,documento", False',
    '    http.setRequestHeader "apikey", chaveCentral',
    '    http.setRequestHeader "Authorization", "Bearer " & chaveCentral',
    '    http.setRequestHeader "Content-Type", "application/json"',
    '    http.setRequestHeader "Prefer", "resolution=ignore-duplicates,return=minimal"',
    '    http.send "[" & histJson & "]"',
    '    If Err.Number <> 0 Then',
    '        nHistoricoFalha = nHistoricoFalha + qtd',
    '        Registrar "ERRO ao gravar no acompanhamento da Central: " & Err.Description',
    '    ElseIf http.Status >= 300 Then',
    '        nHistoricoFalha = nHistoricoFalha + qtd',
    '        Registrar "ERRO ao gravar no acompanhamento da Central (HTTP " & http.Status & "): " & Left(http.responseText, 300)',
    '    Else',
    '        nHistorico = nHistorico + qtd',
    '    End If',
    '    Err.Clear',
    'End Sub',
    '',
    'Private Sub EnviarPartidas(linhasJson, qtd)',
    '    Dim http',
    '    On Error Resume Next',
    '    Set http = CreateObject("MSXML2.XMLHTTP.6.0")',
    '    http.Open "POST", urlCentral & "/rest/v1/ctes_lancamentos_sap?on_conflict=chave", False',
    '    http.setRequestHeader "apikey", chaveCentral',
    '    http.setRequestHeader "Authorization", "Bearer " & chaveCentral',
    '    http.setRequestHeader "Content-Type", "application/json"',
    '    http.setRequestHeader "Prefer", "resolution=ignore-duplicates,return=minimal"',
    '    http.send "[" & linhasJson & "]"',
    '    If Err.Number <> 0 Then',
    '        nPartidasFalha = nPartidasFalha + qtd',
    '        Registrar "ERRO ao gravar partidas na Central: " & Err.Description',
    '    ElseIf http.Status >= 300 Then',
    '        nPartidasFalha = nPartidasFalha + qtd',
    '        Registrar "ERRO ao gravar partidas na Central (HTTP " & http.Status & "): " & Left(http.responseText, 300)',
    '    Else',
    '        nPartidas = nPartidas + qtd',
    '    End If',
    '    Err.Clear',
    'End Sub',
    '',
    "' Valor do CT-e (valor_cte) na base da Central, em lotes de 40 chaves.",
    'Private Function BuscarValoresCentral(miros)',
    '    Dim d, chavesL, i, lista, http, resp, k, p, q, txt',
    '    Set d = CreateObject("Scripting.Dictionary")',
    '    Set BuscarValoresCentral = d',
    '    If miros.Count = 0 Then Exit Function',
    '    chavesL = miros.Keys',
    '    On Error Resume Next',
    '    For i = 0 To UBound(chavesL) Step 40',
    '        lista = ""',
    '        For p = i To i + 39',
    '            If p > UBound(chavesL) Then Exit For',
    '            If lista <> "" Then lista = lista & ","',
    '            lista = lista & chavesL(p)',
    '        Next',
    '        Set http = CreateObject("MSXML2.XMLHTTP.6.0")',
    '        http.Open "GET", urlCentral & "/rest/v1/realizado_local_ctes?select=chave_cte,valor_cte&chave_cte=in.(" & lista & ")", False',
    '        http.setRequestHeader "apikey", chaveCentral',
    '        http.setRequestHeader "Authorization", "Bearer " & chaveCentral',
    '        http.send',
    '        If Err.Number = 0 And http.Status < 300 Then',
    '            resp = http.responseText',
    '            For p = i To i + 39',
    '                If p > UBound(chavesL) Then Exit For',
    '                k = chavesL(p)',
    '                q = InStr(resp, """chave_cte"":""" & k & """")',
    '                If q > 0 Then',
    '                    q = InStr(q, resp, """valor_cte"":")',
    '                    If q > 0 Then',
    '                        txt = Mid(resp, q + 12, 20)',
    '                        If Left(txt, 4) <> "null" Then',
    '                            If Val(txt) > 0 Then d(k) = Val(txt)',
    '                        End If',
    '                    End If',
    '                End If',
    '            Next',
    '        Else',
    '            Registrar "aviso: nao consegui ler o valor dos CT-e na Central (" & Err.Description & ")"',
    '        End If',
    '        Err.Clear',
    '    Next',
    'End Function',
    '',
    "' Log do SAP (todas as situacoes) so das chaves trabalhadas, exportado para a pasta de trabalho.",
    'Private Function ExportarSituacao(lista, n)',
    '    Dim txt, i, t, passoS, f',
    '    ExportarSituacao = False',
    '    txt = ""',
    '    For i = 0 To n - 1',
    '        txt = txt & lista(i) & vbCrLf',
    '    Next',
    '    On Error Resume Next',
    '    For Each f In Workbooks',
    `        If LCase(Left(f.Name, ${ARQ_SITUACAO.length})) = "${ARQ_SITUACAO.toLowerCase()}" Then f.Close False`,
    '    Next',
    `    Kill PASTA & "\\${ARQ_SITUACAO}*"`,
    '    Err.Clear',
    '    On Error GoTo Falhou',
    '    passoS = "abrir a transacao"',
    '    AbrirTransacao',
    `    ${s('wnd[0]/usr/ctxtS_DATA-LOW')}.Text = dataIni`,
    `    ${s('wnd[0]/usr/ctxtS_DATA-HIGH')}.Text = dataFim`,
    '    passoS = "colar as chaves"',
    '    Copiar txt',
    `    ${s('wnd[0]/usr/btn%_S_CHAVE_%_APP_%-VALU_PUSH')}.press`,
    `    ${s('wnd[1]/tbar[0]/btn[16]')}.press`,
    `    ${s('wnd[1]/tbar[0]/btn[24]')}.press`,
    `    ${s('wnd[1]/tbar[0]/btn[8]')}.press`,
    '    FecharCopia',
    `    ${s('wnd[0]/usr/chkP_ERRO')}.Selected = False`,
    `    ${s('wnd[0]/usr/chkP_TODE')}.Selected = True`,
    '    passoS = "executar"',
    `    ${s('wnd[0]/tbar[1]/btn[8]')}.press`,
    '    passoS = "exportar"',
    `    ${s('wnd[0]/tbar[1]/btn[43]')}.press`,
    `    ${s(`${EXPORT}/txtGS_EXPORT-FILE_NAME`)}.Text = "${ARQ_SITUACAO}"`,
    `    ${s(`${EXPORT}/cmbGS_EXPORT-FORMAT`)}.SetFocus`,
    `    ${s('wnd[1]/tbar[0]/btn[20]')}.press`,
    `    ${s('wnd[1]/usr/ctxtDY_PATH')}.Text = PASTA`,
    `    ${s('wnd[1]/usr/ctxtDY_PATH')}.SetFocus`,
    `    ${s('wnd[1]/tbar[0]/btn[0]')}.press`,
    '    On Error GoTo 0',
    '    For t = 1 To 120',
    `        If Dir(PASTA & "\\${ARQ_SITUACAO}*") <> "" Then Exit For`,
    '        Application.Wait Now + TimeSerial(0, 0, 1)',
    '    Next',
    `    If Dir(PASTA & "\\${ARQ_SITUACAO}*") = "" Then`,
    '        Registrar "partidas: o SAP nao gravou a consulta do log; nada gravado na base"',
    '        Exit Function',
    '    End If',
    '    Application.Wait Now + TimeSerial(0, 0, 3)',
    '    ExportarSituacao = True',
    '    Exit Function',
    'Falhou:',
    '    FecharCopia',
    '    Registrar "partidas: falhou ao consultar o log (" & passoS & "): " & Err.Description & "; nada gravado na base"',
    'End Function',
    '',
    "' Le a consulta: chave -> documento da MIRO (so quem tem) e chave -> transportadora.",
    'Private Function LerSituacao(miros, transps, pedidos, empresas)',
    '    Dim nome, wb, ws, i, c, linCab, cChave, cMiro, cTransp, cPed, cEmp, ultima, ultCol, h, k, doc',
    '    LerSituacao = False',
    `    nome = Dir(PASTA & "\\${ARQ_SITUACAO}*")`,
    '    On Error Resume Next',
    '    Set wb = Workbooks(nome)',
    '    On Error GoTo 0',
    '    If IsEmpty(wb) Then Set wb = Workbooks.Open(PASTA & "\\" & nome, False, True)',
    '    Set ws = wb.Worksheets(1)',
    '    linCab = 0',
    '    ultCol = ws.UsedRange.Column + ws.UsedRange.Columns.Count - 1',
    '    For i = 1 To 30',
    '        cChave = 0',
    '        cMiro = 0',
    '        cTransp = 0',
    '        cPed = 0',
    '        cEmp = 0',
    '        For c = 1 To ultCol',
    '            h = LCase(Replace(Trim(CStr(ws.Cells(i, c).Value)), " ", ""))',
    '            If h = "chavecte" Then cChave = c',
    '            If h = "documentodamirocte" Or h = "docmirocte" Then cMiro = c',
    '            If h = "transportadora" Then cTransp = c',
    '            If h = "documentodecompras" Or h = "doc.compra" Then cPed = c',
    '            If h = "empresa" Or h = "empr." Then cEmp = c',
    '        Next',
    '        If cChave > 0 Then',
    '            linCab = i',
    '            Exit For',
    '        End If',
    '    Next',
    '    If cChave = 0 Or cMiro = 0 Then',
    '        wb.Close False',
    '        Registrar "partidas: a consulta do log nao tem as colunas Chave CTe / Documento da Miro CTe; nada gravado na base"',
    '        Exit Function',
    '    End If',
    '    ultima = ws.Cells(ws.Rows.Count, cChave).End(-4162).Row',
    '    For i = linCab + 1 To ultima',
    '        k = SoDigitos(CStr(ws.Cells(i, cChave).Text))',
    '        If Len(k) <> 44 Then k = SoDigitos(CStr(ws.Cells(i, cChave).Value))',
    '        doc = SoDigitos(CStr(ws.Cells(i, cMiro).Text))',
    '        If Len(k) = 44 And Len(doc) >= 6 And Val(doc) > 0 Then',
    '            miros(k) = doc',
    '            If cTransp > 0 Then transps(k) = Trim(CStr(ws.Cells(i, cTransp).Value)) Else transps(k) = ""',
    '            If cPed > 0 Then pedidos(k) = Trim(CStr(ws.Cells(i, cPed).Text)) Else pedidos(k) = ""',
    '            If cEmp > 0 Then empresas(k) = Trim(CStr(ws.Cells(i, cEmp).Text)) Else empresas(k) = ""',
    '        End If',
    '    Next',
    '    wb.Close False',
    '    LerSituacao = True',
    'End Function',
    '',
    'Private Function JsonTxt(t)',
    '    JsonTxt = Replace(Replace(Replace(Replace(CStr(t), "\\", "\\\\"), """", "\\"""), vbCr, " "), vbLf, " ")',
    'End Function',
    '',
    'Private Function NumJson(v)',
    '    NumJson = Replace(CStr(v), ",", ".")',
    'End Function',
    '',
    'Private Sub AnexarTexto(caminho, texto)',
    '    Dim h',
    '    On Error Resume Next',
    '    h = FreeFile',
    '    Open caminho For Append As #h',
    '    Print #h, texto',
    '    Close #h',
    'End Sub',
  ];
}
