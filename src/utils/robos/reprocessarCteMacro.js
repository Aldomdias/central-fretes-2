function semAcento(texto = '') {
  return String(texto ?? '').normalize('NFD').replace(/[̀-ͯ]/g, '');
}

function assinatura(texto) {
  let h = 5381;
  for (let i = 0; i < texto.length; i += 1) h = ((h * 33) ^ texto.charCodeAt(i)) >>> 0;
  return h.toString(16).padStart(8, '0');
}

