-- Cadastro de referencia: codigo do Centro/CD -> cidade. Usado para enriquecer
-- (exibir e filtrar) a coluna 'CDs com Saldo na Venda' da Auditoria E-commerce.
create table if not exists cd_centros (
  codigo text primary key,
  cidade text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table cd_centros enable row level security;

drop policy if exists cd_centros_select on cd_centros;
create policy cd_centros_select on cd_centros for select using (true);

drop policy if exists cd_centros_insert on cd_centros;
create policy cd_centros_insert on cd_centros for insert with check (true);

drop policy if exists cd_centros_update on cd_centros;
create policy cd_centros_update on cd_centros for update using (true) with check (true);

drop policy if exists cd_centros_delete on cd_centros;
create policy cd_centros_delete on cd_centros for delete using (true);

