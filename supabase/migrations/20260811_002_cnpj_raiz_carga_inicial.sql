update public.transportadoras as transportadora
set
  cnpj = carga.cnpj,
  cnpj_raiz = carga.cnpj_raiz
from carga
where lower(btrim(transportadora.nome)) = lower(btrim(carga.nome))
  and (transportadora.cnpj_raiz is null or transportadora.cnpj_raiz = carga.cnpj_raiz);

update public.tabelas_negociacao as negociacao
set
  cnpj_transportadora = transportadora.cnpj,
  cnpj_raiz_transportadora = transportadora.cnpj_raiz
from public.transportadoras as transportadora
where lower(btrim(negociacao.transportadora)) = lower(btrim(transportadora.nome))
  and transportadora.cnpj_raiz is not null
  and negociacao.cnpj_raiz_transportadora is null;
